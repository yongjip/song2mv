def _glyphs() -> dict[str, np.ndarray]:
    out = {" ": np.zeros((ROWS, COLS), bool)}
    for line in _TABLE.strip().splitlines():
        rows = [[b == "1" for b in r] for r in line[2:].split()]
        out[line[0]] = np.array(rows + [[False] * COLS] * (ROWS - len(rows)), bool)
    return out


GLYPHS = _glyphs()


@lru_cache(maxsize=512)
def _mask(ch: str, scale: int) -> np.ndarray:
    return GLYPHS.get(ch, GLYPHS["?"]).repeat(scale, 0).repeat(scale, 1)


def width(text: str, scale: int) -> int:
    return max(0, len(text) * ADVANCE - 1) * scale


def draw(img: np.ndarray, x: int, y: int, text: str, color: tuple[int, int, int], scale: int, right: int) -> int:
    """Draws `text` with its top-left corner at (x, y), each bit a square of `scale` pixels, and stops before a letter
    would cross `right`. Returns where the next letter would start."""
    for ch in text:
        if x + COLS * scale > right:
            break
        m = _mask(ch, scale)
        img[y: y + m.shape[0], x: x + m.shape[1]][m] = color
        x += ADVANCE * scale
    return x
